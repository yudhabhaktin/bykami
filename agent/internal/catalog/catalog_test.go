func TestAllPackagesValidate(t *testing.T) {
	all, err := catalog.All()
	if err != nil {
		t.Fatalf("catalog: %v", err)
	}
	if len(all) == 0 {
		t.Fatal("the booth has nothing to sell")
	}

	seen := map[string]bool{}
	for _, p := range all {
		if seen[p.ID] {
			t.Fatalf("duplicate package id %q", p.ID)
		}
		seen[p.ID] = true
	}
}

